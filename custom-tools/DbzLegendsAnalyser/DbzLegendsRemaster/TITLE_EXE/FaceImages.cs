    // 696 bytes. Every game-side callee is already ported — WaitSearchFile @ 0x80057F80,
    // ReadCDData @ 0x80057E40, FUN_80035778 @ 0x80035778 and LoadImageInVram @ 0x80057BB4 — and the
    // two SDK ones, CdPosToInt and CdIntToPos, are real in LibCd as of 2026-08-30.
    //
    // THE SECOND HALF TILES DAT_80096664 EXACTLY, which is the self-check that its six absolute
    // addresses were read correctly. Relative to 0x80096664 they are +0x000 (0x80 x 1), +0x100
    // (0x100 x 1), +0x300 (0x20 x 0x80), +0x2300 (0x28 x 0x70), +0x4600 (0x28 x 0x60) and +0x6400
    // (0x40 x 0x20); each block ends precisely where the next begins, and the last ends at +0x7400,
    // inside the 0x8000-byte staging buffer.
    //
    // The three portrait tiles come out of BYTE_ARRAY_801d2000 at +0x20, +0x4A0 and +0x920 with a
    // 0xC x 0x30 rect each, that is 0x480 bytes apiece, so they tile +0x20..+0xDA0 of the 0x1000
    // bytes cdlFile2.size asks for.
    internal static void LoadFACE_B()
    {
        short sVar1;
        int puVar2;
        int psVar3;
        int offset;
        int puVar4;
        int puVar5;
        int iVar6;
        int i;

        // The original's CdlFILE embeds its CdlLOC by value; the port's is a reference field, so
        // each of the two stack records is given one here. cdlFile is filled by CdSearchFile;
        // cdlFile2 is never searched and receives its position from CdIntToPos alone.
        CdlFILE cdlFile = new() { pos = new CdlLOC() };
        CdlFILE cdlFile2 = new() { pos = new CdlLOC() };
        int local_30;

        i = 0;
        iVar6 = 0xa00000;
        puVar4 = Dat8007a220Address;
        puVar5 = Dat8007a22aAddress;
        puVar2 = PTR_DAT_8007a554[GteScratch.DAT_1f80012c];
        offset = 0;
        TITLE_EXE_exe.WaitSearchFile("\\CHR_DATA\\FACE.B;1".ToCharArray(), cdlFile);
        local_30 = CdPosToInt(cdlFile.pos);
        cdlFile2.size = 0x1000;
        psVar3 = puVar2 + 0x52;
        do
        {
            sVar1 = (short)PsxRam.ReadU16(psVar3);
            psVar3 = psVar3 + 2;
            if (sVar1 != 0)
            {
                CdIntToPos(local_30 + ((sVar1 + -1) * 2), cdlFile2.pos);
                TITLE_EXE_exe.ReadCDData(cdlFile2, ByteArray801d2000Address, 0);
                DisplayMachine.LoadImageInVram(
                    ToWordBuffer(LoadingScreen.BYTE_ARRAY_801d2000, 0x20, 0xc * 0x30 * 2),
                    PsxRam.ReadU16(puVar4),
                    PsxRam.ReadU16(Dat8007a222Address + offset), 0xc, 0x30, '\0');
                DisplayMachine.LoadImageInVram(
                    ToWordBuffer(LoadingScreen.BYTE_ARRAY_801d2000, 0x4a0, 0xc * 0x30 * 2),
                    PsxRam.ReadU16(Dat8007a224Address + offset),
                    PsxRam.ReadU16(Dat8007a226Address + offset), 0xc, 0x30, '\0');
                DisplayMachine.LoadImageInVram(
                    ToWordBuffer(LoadingScreen.BYTE_ARRAY_801d2000, 0x920, 0xc * 0x30 * 2),
                    PsxRam.ReadU16(Dat8007a228Address + offset),
                    PsxRam.ReadU16(puVar5), 0xc, 0x30, '\0');

                // iVar6 starts at 0xA00000 and grows by 0x100000 every turn of the loop — the
                // increment is OUTSIDE this `if`, so a skipped entry still consumes its column.
                // The upload takes the top halfword, so x runs 0xA0, 0xB0, 0xC0 ... one CLUT strip
                // per slot.
                DisplayMachine.LoadImageInVram(
                    ToWordBuffer(LoadingScreen.BYTE_ARRAY_801d2000, 0, 0x10 * 1 * 2),
                    (ushort)((uint)iVar6 >> 0x10), 0x1e6, 0x10, 1, '\x01');
            }

            iVar6 = iVar6 + 0x100000;
            puVar5 = puVar5 + 12;
            puVar4 = puVar4 + 12;
            i = i + 1;
            offset = offset + 0xc;
        } while (i < 0xc);

        TITLE_EXE_exe.WaitSearchFile("\\CHR_DATA\\OV_CHR_A.B;1".ToCharArray(), cdlFile);

        // cdlFile is REUSED, and the size CdSearchFile just filled in is overwritten with 0x3800 —
        // seven sectors — before the read. The file on the disc is much larger than that; only its
        // head is wanted.
        cdlFile.size = 0x3800;
        TITLE_EXE_exe.ReadCDData(cdlFile, ByteArray801d2000Address, 0);
