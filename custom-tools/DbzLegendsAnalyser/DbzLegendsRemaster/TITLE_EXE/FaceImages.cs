    // JUSTIFICATION: C# language bridge only
    // RELATION: LoadImageInVram @ 0x80057BB4 takes the u_long * form, and every source here is a
    // label INSIDE a larger buffer, so this bridge takes the start offset the label stands for as
    // well as the byte count. Same bridge as the private ones in TitleImages, LoadingScreen and
    // SelectScreenSetup, which only ever start at zero.
    private static ulong[] ToWordBuffer(byte[] source, int offset, int byteCount)
    {
        if (offset < 0 || offset >= source.Length)
        {
            offset = 0;
        }

        if (byteCount <= 0 || offset + byteCount > source.Length)
        {
            byteCount = source.Length - offset;
        }

        int words = (byteCount + 3) / 4;
        ulong[] result = new ulong[words];
        for (int i = 0; i < words; i++)
        {
            int o = i * 4;
            uint word = source[offset + o];
            if (o + 1 < byteCount) word |= (uint)source[offset + o + 1] << 8;
            if (o + 2 < byteCount) word |= (uint)source[offset + o + 2] << 16;
            if (o + 3 < byteCount) word |= (uint)source[offset + o + 3] << 24;
            result[i] = word;
        }

        return result;
    }

    // JUSTIFICATION: C# language bridge only
    // RELATION: lets the overlay's address resolver map the two .data spans above, since LoadFACE_B
    // reads both by raw PSX address exactly as the original does — the coordinate table through two
    // roaming cursors and four label-plus-offset reads, the record through a pointer taken out of
    // PTR_DAT_8007a554.
    internal static (byte[] Buffer, int Offset)? Resolve(int address)
    {
        int offset = address - Dat8007a220Address;
        if (offset >= 0 && offset < DAT_8007a220.Length)
        {
            return (DAT_8007a220, offset);
        }

        offset = address - Dat80079b34Address;
        if (offset >= 0 && offset < DAT_80079b34.Length)
        {
            return (DAT_80079b34, offset);
        }

        return null;
    }
