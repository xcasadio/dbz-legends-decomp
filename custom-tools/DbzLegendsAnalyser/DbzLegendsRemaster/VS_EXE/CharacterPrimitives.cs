// THE FIGHTER AURA PRIMITIVE BUILDER — what gives a fighter's aura something to draw. The fighter
// itself is a sprite (DrawSpriteGroup); the six 0x1E58-byte workspaces below are FighterAuraRecords
// (docs/types/DbzLegendsTypes.h), one per fighter, read at their renderer RenderFighterAuraPass.
//
// FighterSubstitution.ActivateFighterInSlot calls BuildFighterAuraPrimitives as its second act, before it even
// publishes the fighter's own character-data pointer, and until this file landed that call went to
// an empty stub: every fighter on the field had its state, its input and its position, and not one
// primitive to submit.
//
// WHAT IT BUILDS. FighterSetup.cs owns the six 0x1E58-byte character workspaces at DAT_8008DA48;
// this file fills one of them. The layout it writes, read off the code rather than off a struct:
//   +0x00  the new character id, +0x02 the slot -- the pair the search below matches on
//   +0x05  a running primitive-record cursor, advanced by each of the three passes
//   +0x0A / +0x09 / +0x0B  the three passes' own record counts, written by ExpandPrimitiveTemplate
//   +0x14 SVECTOR rot[3], +0x2C SVECTOR pos[3], +0x44 VECTOR scale[3] -- one per template pass,
//         the arguments of RotMatrix / the translation / ScaleMatrix in RenderFighterAuraPass
//   +0x1E44  lastFighterPos, a copy of the fighter's own +0x114 position
//   +0x74    POLY_GT4 prims[100], the GPU packets (0x34 bytes each)
//   +0x14C4  short vertices[100][4][3], the quad corners in model space (0x18 each) that
//            ExpandPrimitiveTemplate copies out of the template's vertex table
//
// THE SEARCH IS THE FIRST THING IT DOES, AND IT CAN FAIL. It walks the six workspaces from slot 5
// down to slot 0 looking for one whose first word equals `(previousCharacterId & 0xFF) |
// ((slotIndex & 0xFF) << 16)`, and returns -1 when none matches, having written nothing. The
// original's own address arithmetic is kept: it starts a byte cursor at 6 * 0x1E58 and adds it to
// 0x8008BBF0, which is DAT_8008DA48 minus one stride, so the first probe lands on slot 5.
//
// THREE PASSES, one per template, and the templates are DATA. ExpandPrimitiveTemplate is handed 1, then 0,
// then 2, and each index picks a record out of the pointer triple at 0x800811B4. Each record is
// {count, vertexTable, indexTable}: the index table holds five halfwords per primitive -- four
// vertex indices and a flag -- and the vertex table three halfwords per vertex. The flag chooses
// between a 0x0C-word primitive with GPU code 0x3C and a 9-word one with code 0x34.
//
// The whole span 0x80080ADC..0x800811BF is embedded byte for byte below, because the code
// DEREFERENCES the pointers inside it: `piVar3[1]` and `piVar3[2]` are addresses, not indices, so
// re-expressing the tables as managed arrays would break the arithmetic the original performs. The
// extents are CLOSED, not assumed -- each record's index table ends exactly where its vertex table
// begins, and record 0's index table ends exactly at record 0's own header:
//   record 0  count 8     vertices 0x80080ADC (15 x 6 bytes)  indices 0x80080B38 (8 x 10)
//   record 1  count 0x28  vertices 0x80080D24 (62 x 6)        indices 0x80080B94 (0x28 x 10)
//   record 2  count 0x28  vertices 0x80081034 (62 x 6)        indices 0x80080EA4 (0x28 x 10)
